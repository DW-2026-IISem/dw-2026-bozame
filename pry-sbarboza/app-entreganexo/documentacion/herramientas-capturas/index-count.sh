#!/usr/bin/env bash
docker exec -i entreganexo-mysql sh -c 'mysql -uroot -p"$MYSQL_ROOT_PASSWORD" entreganexo_express 2>/dev/null' <<'SQL'
SELECT TABLE_NAME, COUNT(DISTINCT INDEX_NAME) AS indices, GROUP_CONCAT(DISTINCT INDEX_NAME ORDER BY INDEX_NAME) AS nombres
FROM information_schema.STATISTICS WHERE TABLE_SCHEMA = DATABASE() GROUP BY TABLE_NAME;
SELECT TABLE_NAME, COUNT(*) AS fks FROM information_schema.TABLE_CONSTRAINTS
WHERE TABLE_SCHEMA = DATABASE() AND CONSTRAINT_TYPE = 'FOREIGN KEY' GROUP BY TABLE_NAME;
SQL
